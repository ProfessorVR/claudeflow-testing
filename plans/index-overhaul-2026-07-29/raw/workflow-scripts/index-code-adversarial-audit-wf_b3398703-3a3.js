phase('Audit')

const audited = await pipeline(
  SCOPES,
  (s) => agent(
    RULES + '\n\nYOUR SCOPE:\n' + s.brief + '\n\n' + [
      'Read the code. Every line in your range. Do not skim and do not summarise the docstrings -- trace the',
      'actual control flow and data flow. Return the structured object with an exhaustive findings list.',
      '30 evidenced findings beats 8 tidy ones. Every finding needs path:line and quoted source.',
    ].join('\n'),
    { label: 'code:' + s.label, phase: 'Audit', schema: CODE_SCHEMA }
  ),
  (res, s) => {
    if (!res || !res.findings) return { scope: s.label, result: res, verified: [] }
    const high = res.findings.filter((f) => f.severity === 'CRITICAL' || f.severity === 'HIGH').slice(0, 7)
    if (!high.length) return { scope: s.label, result: res, verified: [] }
    return parallel(
      high.map((f) => () =>
        agent(
          RULES + '\n\n' + [
            'You are an ADVERSARIAL VERIFIER. Another agent reports this code defect. REFUTE it.',
            'Open the file yourself. Default to refuted=true unless you personally observe the exact lines.',
            '',
            '  scope:       ' + s.label,
            '  severity:    ' + f.severity,
            '  category:    ' + f.category,
            '  location:    ' + f.path_line,
            '  claim:       ' + f.claim,
            '  evidence:    ' + f.evidence,
            '  scenario:    ' + f.failure_scenario,
            '  consequence: ' + f.consequence,
            '',
            'Failure modes to check for in the original claim:',
            '- Line numbers cited against HEAD instead of the dirty working tree, or simply off by one.',
            '- Code that IS reachable via a path the reporter did not trace.',
            '- A guard, try/except, caller-side check, or type narrowing elsewhere that already handles it.',
            '- A silent failure that in fact logs somewhere the reporter did not look.',
            '- Dead code that is actually invoked dynamically, by a script, or by a CLI command.',
            '- A failure scenario that cannot actually be reached with real repo data.',
            '- A consequence that overstates what follows.',
            '',
            'Where possible, demonstrate the defect concretely with a READ-ONLY check (a python3 -c that only',
            'reads, a grep, a tsc --noEmit). Never execute anything that writes.',
            '',
            'Return your verdict.',
          ].join('\n'),
          {
            label: 'verify:' + s.label.slice(0, 16) + ':' + f.category.slice(0, 16),
            phase: 'Verify',
            schema: {
              type: 'object',
              required: ['refuted', 'reasoning', 'evidence_examined'],
              properties: {
                refuted: { type: 'boolean' },
                reasoning: { type: 'string' },
                evidence_examined: { type: 'string' },
                corrected_severity: { type: 'string', enum: ['CRITICAL', 'HIGH', 'MEDIUM', 'LOW', 'NOT-A-DEFECT'] },
                corrected_claim: { type: 'string' },
                demonstration: { type: 'string', description: 'a read-only command and its output that proves or disproves the defect' },
              },
            },
          }
        ).then((v) => ({ finding: f, verdict: v }))
      )
    ).then((verdicts) => ({ scope: s.label, result: res, verified: verdicts.filter(Boolean) }))
  }
)

