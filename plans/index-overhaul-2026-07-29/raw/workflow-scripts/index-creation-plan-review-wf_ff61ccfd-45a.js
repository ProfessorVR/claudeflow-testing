const allDesign = clean.flatMap((c) => ((c.result && c.result.design_inputs) || []).map((g) => '[' + c.scope + '] ' + g))
const allPreserve = clean.flatMap((c) => ((c.result && c.result.what_to_preserve) || []).map((g) => '[' + c.scope + '] ' + g))
const allVerdicts = clean.flatMap((c) => c.verified || [])
const confirmed = allVerdicts.filter((v) => v.verdict && !v.verdict.refuted)
const refuted = allVerdicts.filter((v) => v.verdict && v.verdict.refuted)

log(allDefects.length + ' plan defects, ' + allDesign.length + ' design inputs, ' + allGates.length + ' gates assessed')

