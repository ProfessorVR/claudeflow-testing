phase('Review')

const reviewed = await pipeline(
  SCOPES,
  (s) => agent(
    RULES + '\n\nYOUR SCOPE:\n' + s.brief + '\n\n' + [
      'Read the plans in full and open the products they describe. Trace causation from instruction to defect.',
      'Every finding needs plan-file:line AND, where applicable, the entry path it damaged.',
      'Be exhaustive in design_inputs -- that list is the direct input to a new creation plan, so make each',
      'item concrete enough to execute against, not a slogan.',
    ].join('\n'),
    { label: 'plan:' + s.label, phase: 'Review', schema: PLAN_SCHEMA }
  ),
  (res, s) => {
    if (!res || !res.defects) return { scope: s.label, result: res, verified: [] }
    const high = res.defects.filter((f) => f.severity === 'CRITICAL' || f.severity === 'HIGH').slice(0, 6)
    if (!high.length) return { scope: s.label, result: res, verified: [] }
    return parallel(
      high.map((f) => () =>
        agent(
          RULES + '\n\n' + [
            'You are an ADVERSARIAL VERIFIER. Another agent claims this PLAN defect caused a real product defect.',
            'REFUTE it. Default to refuted=true unless you open both the plan and the product and see the chain.',
            '',
            '  scope:      ' + s.label,
            '  severity:   ' + f.severity,
            '  category:   ' + f.category,
            '  plan line:  ' + f.plan_line,
            '  defect:     ' + f.defect,
            '  observed:   ' + f.consequence_observed,
            '  proposed fix: ' + (f.fix_for_new_plan || '(none)'),
            '',
            'Check for these failure modes:',
            '- The plan line cited does not say what the reporter claims. Read it.',
            '- The plan post-dates the entry it supposedly damaged. Check dates in both.',
            '- The defect has a different cause (compiler behaviour, an executing agent deviating from the plan,',
            '  a later edit) and the plan is blameless.',
            '- The plan DOES specify the thing, elsewhere in the file, and the reporter missed it. Grep the whole plan.',
            '- The observed consequence does not exist in the entry. Verify it on disk.',
            '- The proposed fix would not actually prevent the defect.',
            '',
            'Return your verdict.',
          ].join('\n'),
          {
            label: 'verify:' + s.label.slice(0, 18) + ':' + f.category.slice(0, 14),
            phase: 'Verify',
            schema: {
              type: 'object',
              required: ['refuted', 'reasoning', 'evidence_examined'],
              properties: {
                refuted: { type: 'boolean' },
                reasoning: { type: 'string' },
                evidence_examined: { type: 'string' },
                corrected_severity: { type: 'string', enum: ['CRITICAL', 'HIGH', 'MEDIUM', 'LOW', 'NOT-A-DEFECT'] },
                corrected_claim: { type: 'string' },
                true_cause: { type: 'string', description: 'if the plan is blameless, what actually caused the defect' },
              },
            },
          }
        ).then((v) => ({ defect: f, verdict: v }))
      )
    ).then((verdicts) => ({ scope: s.label, result: res, verified: verdicts.filter(Boolean) }))
  }
)

phase('Synthesize')

const clean = reviewed.filter(Boolean)
const allDefects = clean.flatMap((c) => ((c.result && c.result.defects) || []).map((f) => ({ scope: c.scope, ...f })))
