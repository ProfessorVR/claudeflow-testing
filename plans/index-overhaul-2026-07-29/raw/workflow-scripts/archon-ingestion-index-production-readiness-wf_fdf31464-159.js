phase('Assess')

const assessed = await pipeline(
  SCOPES,
  (s) => agent(
    RULES + '\n\nYOUR SCOPE:\n' + s.brief + '\n\nReturn the structured object. Evidence or it did not happen.',
    { label: 'assess:' + s.label, phase: 'Assess', schema: SCHEMA }
  ),
  (res, s) => {
    if (!res || !res.findings) return { scope: s.label, result: res, verified: [] }
    const load = res.findings.filter((f) => f.severity === 'BLOCKER' || f.severity === 'HIGH').slice(0, 5)
    if (!load.length) return { scope: s.label, result: res, verified: [] }
    return parallel(
      load.map((f) => () =>
        agent(
          RULES + '\n\n' + [
            'ADVERSARIAL VERIFIER. Another agent makes this load-bearing claim. Try to REFUTE it.',
            'Default to refuted=true unless you independently confirm it by opening files or running checks.',
            '',
            '  scope:    ' + s.label,
            '  severity: ' + f.severity,
            '  claim:    ' + f.claim,
            '  evidence: ' + f.evidence,
            '',
            'Check for: a path or line that does not say what is claimed; a capability inferred from a struct',
            'or a doc comment that is never populated or called; a measurement whose method does not support',
            'its conclusion; a rate extrapolated from too small a sample; an estimate with no stated basis;',
            'a problem that is real but already handled elsewhere; a cost that ignores the dissertation timeline.',
          ].join('\n'),
          {
            label: 'verify:' + s.label.slice(0, 20),
            phase: 'Verify',
            schema: {
              type: 'object',
              required: ['refuted', 'reasoning', 'evidence_examined'],
              properties: {
                refuted: { type: 'boolean' },
                reasoning: { type: 'string' },
                evidence_examined: { type: 'string' },
                corrected_claim: { type: 'string' },
              },
            },
          }
        ).then((v) => ({ finding: f, verdict: v }))
      )
    ).then((vs) => ({ scope: s.label, result: res, verified: vs.filter(Boolean) }))
  }
)

